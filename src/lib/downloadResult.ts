import jsPDF from "jspdf";

/** Download agent result as CSV */
export function downloadCSV(agentName: string, result: Record<string, any>) {
  const rows: string[][] = [["Section", "Label", "Detail", "Tag"]];

  if (result.summary) {
    rows.push(["Summary", result.summary, "", ""]);
  }

  (result.sections || []).forEach((sec: any) => {
    (sec.items || []).forEach((item: any) => {
      rows.push([sec.title, item.label, item.detail, item.tag || ""]);
    });
  });

  (result.timeline || []).forEach((t: any) => {
    rows.push(["Timeline", t.phase, t.focus, `${t.pct}%`]);
  });

  (result.risks || []).forEach((r: string, i: number) => {
    rows.push(["Risks", `Risk ${i + 1}`, r, ""]);
  });

  if (result.confidence) {
    rows.push(["Confidence", result.confidence.level, result.confidence.reason, `${result.confidence.score}%`]);
  }

  const csv = rows.map(r => r.map(c => `"${String(c).replace(/"/g, '""')}"`).join(",")).join("\n");
  const blob = new Blob([csv], { type: "text/csv" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${agentName.replace(/\s+/g, "_")}_result.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

/* ─── Brand Palette (unfoldHR) ─── */

const NAVY = "#1a2e4a";
const VIOLET = "#6b5dd3";
const TEAL = "#1d9e75";
const DARK_TEXT = "#1e293b";
const BODY_TEXT = "#334155";
const GRAY = "#64748b";
const LIGHT_GRAY = "#94a3b8";
const CARD_BG = "#f1f5f9";
const AMBER = "#f59e0b";
const AMBER_LIGHT = "#fffbeb";
const AMBER_DARK = "#b45309";
const RED = "#dc2626";
const GREEN = "#16a34a";
const WHITE = "#ffffff";

const PAGE_W = 210;
const PAGE_H = 297;
const MARGIN = 19;
const CONTENT_W = PAGE_W - MARGIN * 2;
const FOOTER_Y = PAGE_H - 14;

function hex(h: string): [number, number, number] {
  const c = h.replace("#", "");
  return [parseInt(c.substring(0, 2), 16), parseInt(c.substring(2, 4), 16), parseInt(c.substring(4, 6), 16)];
}

function wrap(doc: jsPDF, text: string, maxW: number): string[] {
  return doc.splitTextToSize(text, maxW) as string[];
}

function priorityColor(tag: string): string {
  const t = (tag || "").toLowerCase();
  if (t.includes("critical")) return NAVY;
  if (t.includes("high") || t.includes("red")) return RED;
  if (t.includes("medium") || t.includes("moderate") || t.includes("amber")) return AMBER;
  if (t.includes("low") || t.includes("green") || t.includes("good") || t.includes("standard")) return GRAY;
  return VIOLET;
}

/* ─── Footer ─── */
function addFooter(doc: jsPDF, pageNum: number, totalPages: number) {
  // Footer bar
  doc.setFillColor(...hex(NAVY));
  doc.rect(0, PAGE_H - 10, PAGE_W, 10, "F");
  doc.setFontSize(6.5);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...hex("#cbd5e1"));
  doc.text(
    `Generated by unfoldHR  \u2022  www.unfoldhrai.com  \u2022  Confidential  \u2022  Page ${pageNum} of ${totalPages}`,
    PAGE_W / 2,
    PAGE_H - 4,
    { align: "center" }
  );
}

/* ─── Page header strip ─── */
function addHeader(doc: jsPDF, primary: string) {
  doc.setFillColor(...hex(primary));
  doc.rect(0, 0, PAGE_W, 3, "F");
}

/* ─── Ensure space, page-break if needed ─── */
function ensureSpace(doc: jsPDF, y: number, needed: number, pages: number[]): [number, number[]] {
  if (y + needed > FOOTER_Y - 8) {
    doc.addPage();
    pages.push(pages.length + 1);
    addHeader(doc, NAVY);
    return [MARGIN + 8, pages];
  }
  return [y, pages];
}

/* ─── Section heading with colored left bar ─── */
function sectionHeading(doc: jsPDF, y: number, title: string, color: string): number {
  doc.setFillColor(...hex(color));
  doc.roundedRect(MARGIN, y, 3, 12, 1.5, 1.5, "F");
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...hex(NAVY));
  doc.text(title, MARGIN + 8, y + 9);
  return y + 18;
}

/* ─── Draw a pill badge ─── */
function drawPill(doc: jsPDF, x: number, y: number, label: string, bgColor: string, textColor: string = WHITE, w?: number) {
  const pillW = w || Math.max(doc.getTextWidth(label.toUpperCase()) + 6, 16);
  doc.setFillColor(...hex(bgColor));
  doc.roundedRect(x, y, pillW, 5.5, 2.5, 2.5, "F");
  doc.setFontSize(6);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...hex(textColor));
  doc.text(label.toUpperCase(), x + pillW / 2, y + 3.8, { align: "center" });
  return pillW;
}

/* ─── Draw horizontal bar chart row ─── */
function drawBarRow(doc: jsPDF, y: number, label: string, value: number, maxValue: number, tag: string, barColor: string): number {
  const labelW = 58;
  const barMaxW = CONTENT_W - labelW - 30;
  const barW = Math.max(4, (value / maxValue) * barMaxW);

  // Label
  doc.setFontSize(8.5);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...hex(DARK_TEXT));
  doc.text(label, MARGIN + 4, y + 4);

  // Bar
  doc.setFillColor(...hex("#e2e8f0"));
  doc.roundedRect(MARGIN + labelW, y, barMaxW, 6, 2, 2, "F");
  doc.setFillColor(...hex(barColor));
  doc.roundedRect(MARGIN + labelW, y, barW, 6, 2, 2, "F");

  // Value on bar
  doc.setFontSize(7);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...hex(WHITE));
  if (barW > 12) {
    doc.text(String(value), MARGIN + labelW + barW - 3, y + 4.2, { align: "right" });
  } else {
    doc.setTextColor(...hex(DARK_TEXT));
    doc.text(String(value), MARGIN + labelW + barW + 2, y + 4.2);
  }

  // Priority pill
  if (tag) {
    const pillX = PAGE_W - MARGIN - 20;
    drawPill(doc, pillX, y, tag, priorityColor(tag));
  }

  return y + 10;
}

/* ═══════════════════════════════════════════════════════════════
   MAIN PDF EXPORT
   ═══════════════════════════════════════════════════════════════ */
export function downloadPDF(
  agentName: string,
  result: Record<string, any>,
  options?: { logoUrl?: string | null; primaryColor?: string }
) {
  const primary = options?.primaryColor || VIOLET;
  const accent = TEAL;
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  let pages = [1];

  /* ═══════════════════ COVER PAGE ═══════════════════ */
  // Full navy background
  doc.setFillColor(...hex(NAVY));
  doc.rect(0, 0, PAGE_W, PAGE_H, "F");

  // Top accent strip
  doc.setFillColor(...hex(primary));
  doc.rect(0, 0, PAGE_W, 4, "F");

  // Logo
  let contentStartY = 80;
  if (options?.logoUrl) {
    try {
      doc.addImage(options.logoUrl, "PNG", MARGIN, 45, 48, 24);
      contentStartY = 80;
    } catch { /* skip */ }
  }

  // Brand wordmark
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(...hex(accent));
  doc.text("unfoldHR", MARGIN, contentStartY);
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...hex(LIGHT_GRAY));
  doc.text("Direct agents. Stay human.", MARGIN, contentStartY + 7);

  // Divider
  doc.setFillColor(...hex(primary));
  doc.rect(MARGIN, contentStartY + 14, 50, 0.8, "F");

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(30);
  doc.setTextColor(...hex(WHITE));
  const titleLines = wrap(doc, `${agentName} Recommendation`, CONTENT_W);
  titleLines.forEach((line, i) => {
    doc.text(line, MARGIN, contentStartY + 32 + i * 14);
  });

  // Context / date
  const metaY = contentStartY + 32 + titleLines.length * 14 + 12;
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...hex(LIGHT_GRAY));
  doc.text(
    new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" }),
    MARGIN,
    metaY
  );

  if (result.contextLine) {
    doc.setFontSize(9);
    doc.setTextColor(...hex("#94a3b8"));
    doc.text(result.contextLine, MARGIN, metaY + 8);
  }

  // Cover footer
  doc.setFontSize(9);
  doc.setTextColor(...hex(accent));
  doc.text("Powered by unfoldHR AI", MARGIN, PAGE_H - 28);
  doc.setFontSize(7);
  doc.setTextColor(...hex(LIGHT_GRAY));
  doc.text("www.unfoldhrai.com  \u2022  Confidential", MARGIN, PAGE_H - 22);

  /* ═══════════════════ PAGE 1: EXECUTIVE SUMMARY ═══════════════════ */
  doc.addPage();
  pages.push(2);
  addHeader(doc, NAVY);
  let y = MARGIN + 8;

  // ── Executive Summary ──
  if (result.summary) {
    y = sectionHeading(doc, y, "Executive Summary", primary);
    doc.setFontSize(9.5);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...hex(BODY_TEXT));
    const lines = wrap(doc, result.summary, CONTENT_W - 8);
    lines.forEach(line => {
      [y, pages] = ensureSpace(doc, y, 5.5, pages);
      doc.text(line, MARGIN + 8, y);
      y += 4.8;
    });
    y += 8;
  }

  // ── Confidence Score Card ──
  if (result.confidence) {
    [y, pages] = ensureSpace(doc, y, 40, pages);
    y = sectionHeading(doc, y, "Confidence Score", primary);

    const score = result.confidence.score || 0;
    const confColor = score >= 75 ? TEAL : score >= 50 ? AMBER : RED;

    // Card background
    doc.setFillColor(...hex(CARD_BG));
    doc.roundedRect(MARGIN + 4, y, CONTENT_W - 4, 32, 3, 3, "F");

    // Left colored accent
    doc.setFillColor(...hex(confColor));
    doc.roundedRect(MARGIN + 4, y, 3, 32, 1.5, 1.5, "F");

    // Big score
    doc.setFontSize(28);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...hex(confColor));
    doc.text(`${score}%`, MARGIN + 16, y + 18);

    // Level badge
    const levelX = MARGIN + 42;
    doc.setFontSize(13);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...hex(NAVY));
    doc.text(result.confidence.level || "", levelX, y + 12);

    // Reason
    doc.setFontSize(8);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...hex(GRAY));
    const reasonLines = wrap(doc, result.confidence.reason || "", CONTENT_W - 55);
    reasonLines.slice(0, 3).forEach((line, i) => {
      doc.text(line, levelX, y + 18 + i * 4);
    });

    // Progress bar
    const barY = y + 27;
    doc.setFillColor(...hex("#e2e8f0"));
    doc.roundedRect(levelX, barY, 90, 2.5, 1.2, 1.2, "F");
    doc.setFillColor(...hex(confColor));
    doc.roundedRect(levelX, barY, 90 * (score / 100), 2.5, 1.2, 1.2, "F");

    y += 42;
  }

  // ── Key Metrics with horizontal bar chart ──
  const sections = result.sections || [];
  if (sections.length > 0) {
    [y, pages] = ensureSpace(doc, y, 30, pages);
    y = sectionHeading(doc, y, "Key Metrics & Analysis", primary);

    sections.forEach((sec: any) => {
      [y, pages] = ensureSpace(doc, y, 18, pages);

      // Sub-section header
      doc.setFontSize(10);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...hex(primary));
      doc.text(sec.title, MARGIN + 8, y);
      y += 6;

      // Find max numeric value for bar scaling
      const items = sec.items || [];
      let maxVal = 1;
      items.forEach((item: any) => {
        const num = parseFloat(String(item.detail).replace(/[^0-9.]/g, ""));
        if (!isNaN(num) && num > maxVal) maxVal = num;
      });

      const hasNumericData = items.some((item: any) => {
        const num = parseFloat(String(item.detail).replace(/[^0-9.]/g, ""));
        return !isNaN(num) && num > 0;
      });

      if (hasNumericData && items.length >= 3) {
        // Render as horizontal bar chart
        items.forEach((item: any) => {
          [y, pages] = ensureSpace(doc, y, 12, pages);
          const num = parseFloat(String(item.detail).replace(/[^0-9.]/g, "")) || 0;
          const barColor = priorityColor(item.tag || "");
          y = drawBarRow(doc, y, item.label, num, maxVal, item.tag || "", barColor);
        });
      } else {
        // Render as metric cards
        items.forEach((item: any) => {
          [y, pages] = ensureSpace(doc, y, 13, pages);

          // Row background
          doc.setFillColor(...hex(CARD_BG));
          doc.roundedRect(MARGIN + 6, y - 3, CONTENT_W - 6, 10, 1.5, 1.5, "F");

          // Label
          doc.setFontSize(8.5);
          doc.setFont("helvetica", "bold");
          doc.setTextColor(...hex(NAVY));
          doc.text(item.label, MARGIN + 10, y + 3);

          // Detail
          doc.setFont("helvetica", "normal");
          doc.setTextColor(...hex(BODY_TEXT));
          const detailW = CONTENT_W - 78;
          const detailLines = wrap(doc, item.detail, detailW > 0 ? detailW : 55);
          doc.text(detailLines[0] || "", MARGIN + 58, y + 3);

          // Tag pill
          if (item.tag) {
            const pillX = PAGE_W - MARGIN - 22;
            drawPill(doc, pillX, y - 1, item.tag, priorityColor(item.tag));
          }

          y += 11;
        });
      }
      y += 5;
    });
  }

  // ── Timeline (segmented progress bar) ──
  if (result.timeline?.length) {
    [y, pages] = ensureSpace(doc, y, 35, pages);
    y = sectionHeading(doc, y, "Implementation Timeline", accent);

    const timeline = result.timeline;
    const totalPct = timeline.reduce((s: number, t: any) => s + (t.pct || 0), 0) || 100;
    const segBarX = MARGIN + 8;
    const segBarW = CONTENT_W - 8;
    const segBarH = 8;

    // Background
    doc.setFillColor(...hex("#e2e8f0"));
    doc.roundedRect(segBarX, y, segBarW, segBarH, 3, 3, "F");

    // Segments
    const segColors = [NAVY, VIOLET, TEAL, "#8b5cf6", "#0ea5e9"];
    let segX = segBarX;
    timeline.forEach((t: any, i: number) => {
      const w = (t.pct / totalPct) * segBarW;
      const col = segColors[i % segColors.length];
      doc.setFillColor(...hex(col));
      if (i === 0) {
        doc.roundedRect(segX, y, w, segBarH, 3, 3, "F");
        // Fill right corner
        doc.rect(segX + w - 3, y, 3, segBarH, "F");
      } else if (i === timeline.length - 1) {
        doc.roundedRect(segX, y, w, segBarH, 3, 3, "F");
        doc.rect(segX, y, 3, segBarH, "F");
      } else {
        doc.rect(segX, y, w, segBarH, "F");
      }

      // Label on bar
      doc.setFontSize(6);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...hex(WHITE));
      if (w > 15) {
        doc.text(`${t.pct}%`, segX + w / 2, y + segBarH / 2 + 1.5, { align: "center" });
      }
      segX += w;
    });

    y += segBarH + 4;

    // Phase details below
    timeline.forEach((t: any, i: number) => {
      [y, pages] = ensureSpace(doc, y, 14, pages);
      const col = segColors[i % segColors.length];

      // Color dot
      doc.setFillColor(...hex(col));
      doc.circle(MARGIN + 12, y + 2, 2, "F");

      // Phase name
      doc.setFontSize(9);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...hex(NAVY));
      doc.text(t.phase, MARGIN + 18, y + 4);

      // Focus
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...hex(BODY_TEXT));
      doc.setFontSize(8);
      const focusLines = wrap(doc, t.focus, CONTENT_W - 55);
      focusLines.slice(0, 2).forEach((line, li) => {
        doc.text(line, MARGIN + 55, y + 4 + li * 4);
      });

      // Pct
      doc.setFontSize(8);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...hex(col));
      doc.text(`${t.pct}%`, PAGE_W - MARGIN - 2, y + 4, { align: "right" });

      y += 10;
    });
    y += 6;
  }

  // ── Risks & Mitigations (amber-bordered cards) ──
  if (result.risks?.length) {
    [y, pages] = ensureSpace(doc, y, 25, pages);
    y = sectionHeading(doc, y, "Risks & Mitigations", AMBER_DARK);

    result.risks.forEach((r: string) => {
      const riskLines = wrap(doc, r, CONTENT_W - 28);
      const cardH = Math.max(10, riskLines.length * 4.5 + 6);
      [y, pages] = ensureSpace(doc, y, cardH + 3, pages);

      // Amber card background
      doc.setFillColor(...hex(AMBER_LIGHT));
      doc.roundedRect(MARGIN + 6, y - 2, CONTENT_W - 6, cardH, 2, 2, "F");

      // Left amber border
      doc.setFillColor(...hex(AMBER));
      doc.roundedRect(MARGIN + 6, y - 2, 2.5, cardH, 1.2, 1.2, "F");

      // Warning triangle (drawn manually)
      doc.setFillColor(...hex(AMBER_DARK));
      const tx = MARGIN + 14;
      const ty = y + 2;
      doc.triangle(tx, ty - 2.5, tx - 2.5, ty + 2, tx + 2.5, ty + 2, "F");
      doc.setFontSize(6);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...hex(WHITE));
      doc.text("!", tx, ty + 1.2, { align: "center" });

      // Risk text
      doc.setFontSize(8.5);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...hex(DARK_TEXT));
      riskLines.forEach((line, i) => {
        doc.text(line, MARGIN + 22, y + 3 + i * 4.5);
      });

      y += cardH + 3;
    });
    y += 4;
  }

  /* ═══════════════════ FOOTERS ON ALL CONTENT PAGES ═══════════════════ */
  const totalPages = doc.getNumberOfPages();
  for (let i = 2; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(doc, i - 1, totalPages - 1);
  }

  /* ═══════════════════ SAVE ═══════════════════ */
  doc.save(`${agentName.replace(/\s+/g, "_")}_Recommendation.pdf`);
}
